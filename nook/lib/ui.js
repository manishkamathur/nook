export function icon(name, size = 18) {
  const span = document.createElement('span');
  span.className = 'icon';
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${PATHS[name] || ''}</svg>`;
  if (name === 'more') span.querySelector('svg').setAttribute('fill', 'currentColor');
  return span;
}

export function brandMark(size = 22) {
  return h('img', { class: 'brand-mark', src: chrome.runtime.getURL('icons/icon-32.png'), width: size, height: size, alt: '' });
}

let toastRoot;
export function toast(message, { action, onAction, timeout = 4200 } = {}) {
  toastRoot ||= document.getElementById('toasts');
  if (!toastRoot) return;
  const el = h('div', { class: 'toast', role: 'status' },
    h('span', null, message),
    action && h('button', {
      class: 'toast-action',
      onclick: () => { onAction?.(); el.remove(); },
    }, action),
  );
  toastRoot.append(el);
  setTimeout(() => el.classList.add('leaving'), timeout);
  setTimeout(() => el.remove(), timeout + 300);
}

export function applyTheme(theme) {
  const root = document.documentElement;
  if (theme === 'light' || theme === 'dark') root.dataset.theme = theme;
  else delete root.dataset.theme;
}

export function clear(el) {
  while (el.firstChild) el.firstChild.remove();
  return el;
}
